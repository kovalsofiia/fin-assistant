"""Промпт для завдання генерації тестів. Однаковий для всіх моделей і повторів."""

TEST_GENERATION_PROMPT = """Ти — інженер з автоматизованого тестування. Напиши unit-тести на pytest для модуля Python нижче.

Вимоги:
- Тестуй лише публічний інтерфейс: `build_draft` та `draft_model_result` (приватну `_match_category` напряму не тестуй).
- Імпортуй з `agent.drafts` (наприклад: `from agent.drafts import DraftError, build_draft, draft_model_result`).
- Покрий межові випадки: некоректний тип, некоректна сума (нуль, від'ємна, нижче/вище межі), некоректна дата
  (неправильний формат, у майбутньому, надто давня), пошук категорії (знайдена/не знайдена/без урахування регістру),
  округлення суми, обрізання опису, приведення is_fop до bool.
- Використовуй лише pytest (`assert`, `pytest.raises`), без mock-бібліотек — модуль не має побічних ефектів.
- Файл має бути повністю самодостатнім і одразу виконуваним, без TODO чи заглушок.
- Поверни ЛИШЕ код тестів в одному блоці ```python ... ``` без пояснень до чи після.

Код модуля (agent/drafts.py):

```python
{source}
```
"""


def build_prompt(source: str) -> str:
    return TEST_GENERATION_PROMPT.format(source=source)
